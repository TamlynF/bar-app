-- Layer 2: one row per serve, so a half pint and a bottle stop pretending to be
-- the round they are named after. `menu_items.price` stays as the display text
-- the public menu renders; these rows are what the price comparison reads.
create table if not exists public.menu_item_prices (
  id bigint generated by default as identity primary key,
  menu_item_id bigint not null references public.menu_items(id) on delete cascade,
  serve text not null,
  amount numeric(6,2) not null,
  display_order integer not null default 0,
  created_at timestamp with time zone not null default now(),
  created_by bigint references public.employees(id) on delete set null,
  updated_at timestamp with time zone not null default now(),
  updated_by bigint references public.employees(id) on delete set null
);

create index if not exists menu_item_prices_item_idx
  on public.menu_item_prices (menu_item_id, display_order);

create unique index if not exists menu_item_prices_item_serve_idx
  on public.menu_item_prices (menu_item_id, serve);

-- Layer 3: the rounds themselves. Adding "Pint (Cider)" is a row, not a deploy.
-- `serves` is the comma-separated list of serves that can price the round, so a
-- glass of wine can be sold as either "small" or "glass".
create table if not exists public.price_benchmarks (
  id bigint generated by default as identity primary key,
  key text not null unique,
  label text not null,
  serves text not null default 'each',
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  created_by bigint references public.employees(id) on delete set null,
  updated_at timestamp with time zone not null default now(),
  updated_by bigint references public.employees(id) on delete set null
);

