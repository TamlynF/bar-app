// Extracts the theme-only part of the app's globals.css for the mini-package
// Tailwind compile: @custom-variant lines, every @theme / @theme inline block,
// and the custom-property declarations of the token scopes (:root, :host,
// [data-*], .dark), each kept inside its @layer / @media wrappers. Nothing
// else - no @source globs, no @layer utilities, no @utility, no keyframes -
// so `@import "tailwindcss" source(none)` in _tw-input.css really does limit
// the compiled utilities to what poc-src/ uses. Run from the REPO ROOT:
//   node .design-sync/build-tw-theme.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { walkCss, isTokenScope, chainOf } from "./css-walk.mjs";

const SRC = "src/app/globals.css";
const OUT = ".design-sync/.cache/_tw-theme.css";

const css = readFileSync(SRC, "utf8");
const out = [
  "/* Generated by .design-sync/build-tw-theme.mjs from src/app/globals.css -",
  "   theme registrations and token scopes only. Do not edit; rerun the script. */",
];

for (const m of css.matchAll(/^@custom-variant[^;{]*;/gm)) out.push(m[0]);

const themeBlocks = [];
const tokenDecls = [];
walkCss(css, {
  onBlock: (b) => {
    if (/^@theme\b/.test(b.prelude) && b.chain.length === 0) themeBlocks.push(css.slice(b.start, b.end + 1));
  },
  onDecl: (d) => {
    const chain = chainOf(d);
    const parent = chain[chain.length - 1] ?? "";
    const outer = chain.slice(0, -1);
    if (d.name.startsWith("--") && !d.name.startsWith("--tw-") && parent && !parent.startsWith("@") && isTokenScope(parent) && outer.every((p) => /^@(layer|media|supports)\b/.test(p))) {
      tokenDecls.push({ chain, name: d.name, value: d.value });
    }
  },
});

out.push(...themeBlocks);

const groups = [];
for (const d of tokenDecls) {
  const key = d.chain.join(" > ");
  const last = groups[groups.length - 1];
  if (last && last.key === key) last.decls.push(d);
  else groups.push({ key, chain: d.chain, decls: [d] });
}
for (const g of groups) {
  g.chain.forEach((p, i) => out.push(`${"  ".repeat(i)}${p} {`));
  const pad = "  ".repeat(g.chain.length);
  for (const d of g.decls) out.push(`${pad}${d.name}: ${d.value};`);
  for (let i = g.chain.length - 1; i >= 0; i--) out.push(`${"  ".repeat(i)}}`);
}

writeFileSync(OUT, out.join("\n") + "\n");
console.log(`tw-theme: ${themeBlocks.length} @theme block(s), ${tokenDecls.length} token declarations in ${groups.length} scope(s) -> ${OUT}`);
